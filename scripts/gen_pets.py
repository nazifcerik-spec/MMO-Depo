"""Pets (DD-328): 20 species hatched from eggs that raid monsters past level
400 drop. Writes content/pets.yaml (the species and their egg items) and the
names in en, tr, zh-CN and es.

Species rank 1..20 (weakest to best):
  min_mob_level  430..1000: a cleared raid whose boss is at least this level
                 can drop the egg
  egg_pct        50% → 2% geometric: each eligible egg is rolled best first,
                 the first hit drops (one egg at most per member and run)
  hatch_seconds  1 h → 24 h
  power_pct      200% → 257% of the mob curve at the pet's power level
  bonus          what the active pet adds to its owner at level 100
                 (a quarter of it at level 1), 3% → 12%, attack / defense /
                 max HP in turn

Run from the repository root: python scripts/gen_pets.py
"""
import io
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from i18n_util import merge  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), '..', 'content')
L = lambda en, tr, zh, es: dict(en=en, tr=tr, zh=zh, es=es)

SPECIES = [
    ('ember_fox', L('Ember Fox', 'Kor Tilkisi', '余烬狐', 'Zorro de Ascuas')),
    ('moss_turtle', L('Moss Turtle', 'Yosun Kaplumbağası', '苔藓龟', 'Tortuga de Musgo')),
    ('frost_owl', L('Frost Owl', 'Ayaz Baykuşu', '霜之鸮', 'Búho de Escarcha')),
    ('thunder_hare', L('Thunder Hare', 'Gök Gürültüsü Tavşanı', '雷霆野兔', 'Liebre del Trueno')),
    ('shadow_cat', L('Shadow Cat', 'Gölge Kedisi', '暗影猫', 'Gato de las Sombras')),
    ('crystal_beetle', L('Crystal Beetle', 'Kristal Böceği', '水晶甲虫', 'Escarabajo de Cristal')),
    ('storm_hawk', L('Storm Hawk', 'Fırtına Şahini', '风暴鹰', 'Halcón de la Tormenta')),
    ('iron_boar', L('Iron Boar', 'Demir Yaban Domuzu', '钢铁野猪', 'Jabalí de Hierro')),
    ('spirit_wolf', L('Spirit Wolf', 'Ruh Kurdu', '灵狼', 'Lobo Espiritual')),
    ('sand_wyrmling', L('Sand Wyrmling', 'Kum Ejderciği', '沙之幼龙', 'Dragoncito de Arena')),
    ('coral_serpent', L('Coral Serpent', 'Mercan Yılanı', '珊瑚巨蛇', 'Serpiente de Coral')),
    ('lava_salamander', L('Lava Salamander', 'Lav Semenderi', '熔岩火蜥', 'Salamandra de Lava')),
    ('moon_stag', L('Moon Stag', 'Ay Geyiği', '月光雄鹿', 'Ciervo Lunar')),
    ('void_raven', L('Void Raven', 'Boşluk Kuzgunu', '虚空渡鸦', 'Cuervo del Vacío')),
    ('griffin_cub', L('Griffin Cub', 'Grifon Yavrusu', '狮鹫幼崽', 'Cría de Grifo')),
    ('frost_drake', L('Frost Drake', 'Ayaz Ejderi', '寒霜飞龙', 'Draco de Escarcha')),
    ('celestial_lynx', L('Celestial Lynx', 'Göksel Vaşak', '天穹猞猁', 'Lince Celestial')),
    ('phoenix_chick', L('Phoenix Chick', 'Anka Yavrusu', '凤凰雏鸟', 'Polluelo de Fénix')),
    ('star_dragon', L('Star Dragon', 'Yıldız Ejderi', '星辰巨龙', 'Dragón Estelar')),
    ('eternal_kirin', L('Eternal Kirin', 'Ebedi Kirin', '永恒麒麟', 'Kirin Eterno')),
]
EGG = L('{} Egg', '{} Yumurtası', '{}蛋', 'Huevo de {}')
TARGETS = ['attack', 'defense', 'hp_max']
N = len(SPECIES)

pets, items = [], []
names = {k: {} for k in ('en', 'tr', 'zh', 'es')}
for i, (code, name) in enumerate(SPECIES):
    t = i / (N - 1)
    rank = i + 1
    egg_pct = round(50 * (2 / 50) ** t, 2)
    pets.append('\n'.join([
        '  - code: ' + code,
        '    display_name_key: pet.' + code,
        '    rank: %d' % rank,
        '    min_mob_level: %d' % (400 + 30 * rank),
        '    egg_pct: %g' % egg_pct,
        '    hatch_seconds: %d' % round(3600 + t * 23 * 3600),
        '    power_pct: %d' % (200 + 3 * i),
        '    bonus: { kind: mult_add, target: %s, amount: %g }' % (TARGETS[i % 3], round(0.03 + t * 0.09, 4)),
    ]))
    egg = 'pet_egg_' + code
    items.append('\n'.join([
        '  - code: ' + egg,
        '    display_name_key: item.' + egg,
        '    item_class: misc',
        '    item_subclass: pet_egg',
        '    min_level: 1',
        '    base_value_copper: %d' % round(50000 * 1.25 ** i),
        '    base_weight_g: 500',
        '    stackable: true',
        '    max_stack: 99',
        '    bind_kind: boe',
    ]))
    for lang in names:
        names[lang]['pet.' + code] = name[lang]
        names[lang]['item.' + egg] = EGG[lang].format(name[lang])

out = ('# Pets (DD-328) — generated by scripts/gen_pets.py; edit the script, not this file.\n'
       '# Eggs drop from cleared raids whose boss is at least min_mob_level; each\n'
       '# eligible egg is rolled best first at egg_pct, the first hit drops.\n\n'
       'pets:\n' + '\n\n'.join(pets) + '\n\nitems:\n' + '\n\n'.join(items) + '\n')
with io.open(os.path.join(ROOT, 'pets.yaml'), 'w', encoding='utf-8', newline='\n') as f:
    f.write(out)
merge(names)
print('pets', len(pets))
