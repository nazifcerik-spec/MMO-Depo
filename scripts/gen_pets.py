"""Pets (DD-328, DD-334): 50 species hatched from eggs that raid monsters past level
400 drop. Writes content/pets.yaml (the species and their egg items) and the
names in en, tr, zh-CN and es.

Species rank 1..50 (weakest to best):
  min_mob_level  412..1000: a cleared raid whose boss is at least this level
                 can drop the egg
  egg_pct        50% → 2% geometric: each eligible egg is rolled best first,
                 the first hit drops (one egg at most per member and run)
  hatch_seconds  1 h → 24 h
  power_pct      200% → 257% of the mob curve at the pet's power level
  bonus          what the active pet adds to its owner at level 100
                 (a quarter of it at level 1), 3% → 12%, attack / defense /
                 max HP in turn

Run from the repository root: python scripts/gen_pets.py
"""
import io
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from i18n_util import merge  # noqa: E402

ROOT = os.path.join(os.path.dirname(__file__), '..', 'content')
L = lambda en, tr, zh, es: dict(en=en, tr=tr, zh=zh, es=es)

from pet_data import SPECIES as _S  # noqa: E402
from pet_lore import ELEMENTS, LORE  # noqa: E402

SPECIES = [(c, L(en, tr, zh, es)) for c, en, tr, zh, es in _S]
EGG = L('{} Egg', '{} Yumurtası', '{}蛋', 'Huevo de {}')
TARGETS = ['attack', 'defense', 'hp_max']
N = len(SPECIES)

pets, items = [], []
names = {k: {} for k in ('en', 'tr', 'zh', 'es')}
for i, (code, name) in enumerate(SPECIES):
    t = i / (N - 1)
    rank = i + 1
    egg_pct = round(50 * (2 / 50) ** t, 2)
    pets.append('\n'.join([
        '  - code: ' + code,
        '    display_name_key: pet.' + code,
        '    rank: %d' % rank,
        '    min_mob_level: %d' % (400 + round(600 * rank / N)),
        '    egg_pct: %g' % egg_pct,
        '    hatch_seconds: %d' % round(3600 + t * 23 * 3600),
        '    power_pct: %d' % round(200 + 57 * t),
        '    bonus: { kind: mult_add, target: %s, amount: %g }' % (TARGETS[i % 3], round(0.03 + t * 0.09, 4)),
        '    element: ' + LORE[code][0],
    ]))
    egg = 'pet_egg_' + code
    items.append('\n'.join([
        '  - code: ' + egg,
        '    display_name_key: item.' + egg,
        '    item_class: misc',
        '    item_subclass: pet_egg',
        '    min_level: 1',
        '    base_value_copper: %d' % round(50000 * 1.25 ** (19 * t)),
        '    base_weight_g: 500',
        '    stackable: true',
        '    max_stack: 99',
        '    bind_kind: boe',
    ]))
    _, creature, habitat, story = LORE[code]
    for lang in names:
        names[lang]['pet.' + code] = name[lang]
        names[lang]['item.' + egg] = EGG[lang].format(name[lang])
        # The pet index (DD-342): creature, habitat and a short story.
        names[lang]['pet.%s.creature' % code] = creature[lang]
        names[lang]['pet.%s.habitat' % code] = habitat[lang]
        names[lang]['pet.%s.story' % code] = story[lang]
for element, title in ELEMENTS.items():
    for lang in names:
        names[lang]['element.' + element] = title[lang]

out = ('# Pets (DD-328, DD-334) — generated by scripts/gen_pets.py; edit the script, not this file.\n'
       '# Eggs drop from cleared raids whose boss is at least min_mob_level; each\n'
       '# eligible egg is rolled best first at egg_pct, the first hit drops.\n\n'
       'pets:\n' + '\n\n'.join(pets) + '\n\nitems:\n' + '\n\n'.join(items) + '\n')
with io.open(os.path.join(ROOT, 'pets.yaml'), 'w', encoding='utf-8', newline='\n') as f:
    f.write(out)
merge(names)
print('pets', len(pets))
