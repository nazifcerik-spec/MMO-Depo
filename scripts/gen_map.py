"""Travel map positions (DD-279).

The world is one road from the starting city to the last zone (region links)
with each zone's dungeon beside it. The map lays the road out as a snake,
three regions a row, one band per continent (its hub on top); a dungeon sits
just below and right of its zone. Positions are map units; the client draws
the map from them. Writes content/map.yaml.

Run from the repository root after gen_world.py: python scripts/gen_map.py
"""
import io
import os

import yaml

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'content')
COLS = [130, 380, 630]
ROW, HEADER, GAP = 230, 120, 110  # row height, hub-to-first-row, band gap
DUNGEON = (90, 100)  # offset from the zone: below its name

with io.open(os.path.join(ROOT, 'regions.yaml'), encoding='utf-8') as f:
    doc = yaml.safe_load(f)
regions = {r['code']: r for r in doc['regions']}
adj = {}
for l in doc['region_links']:
    adj.setdefault(l['region_a_code'], []).append(l['region_b_code'])
    adj.setdefault(l['region_b_code'], []).append(l['region_a_code'])


def continent(code):
    while regions[code].get('parent_code'):
        code = regions[code]['parent_code']
    return code


# The road: from the starting city along the links.
road, prev = [next(c for c, r in regions.items() if r.get('is_starting'))], None
while True:
    nxt = [n for n in adj.get(road[-1], []) if n != prev and n not in road]
    if not nxt:
        break
    prev = road[-1]
    road.append(nxt[0])
on_road = set(road)

pos, y, last_x = {}, 80, None
bands = []
for code in road:
    c = continent(code)
    if not bands or bands[-1][0] != c:
        bands.append((c, []))
    bands[-1][1].append(code)
for cont, codes in bands:
    pos[cont] = (COLS[1], y)
    y += HEADER
    for i in range(0, len(codes), 3):
        row = codes[i:i + 3]
        left_first = last_x is None or last_x <= COLS[1]
        xs = COLS if left_first else COLS[::-1]
        for code, x in zip(row, xs):
            pos[code] = (x, y)
            last_x = x
        y += ROW
    y += GAP - ROW + ROW // 2

for code, r in regions.items():  # dungeons beside their zone
    if code not in pos and r.get('parent_code') in pos and r['kind'] == 'dungeon':
        px, py = pos[r['parent_code']]
        pos[code] = (px + DUNGEON[0], py + DUNGEON[1])
missing = sorted(set(regions) - set(pos))
assert not missing, 'not placed: %s' % missing

out = ['# Travel map positions (DD-279), map units. Generated by scripts/gen_map.py.',
       'positions:'] + ['  %s: [%d, %d]' % (code, x, y) for code, (x, y) in sorted(pos.items(), key=lambda kv: (kv[1][1], kv[1][0]))]
with io.open(os.path.join(ROOT, 'map.yaml'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('\n'.join(out) + '\n')
print('regions', len(pos), 'road', len(road), 'height', max(p[1] for p in pos.values()))
